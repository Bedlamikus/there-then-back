/*
 * РУКОВОДСТВО ПО НАСТРОЙКЕ ИКОНОК В ИНВЕНТАРЕ
 * ==========================================
 * 
 * ProjectileInventory теперь поддерживает индивидуальные иконки для каждого снаряда!
 * 
 * НАСТРОЙКА В ИНСПЕКТОРЕ:
 * =======================
 * 
 * 1. Projectile Prefabs:
 *    - projectilePrefabs[] - массив префабов снарядов
 *    - projectileIcons[] - массив иконок (Sprite) для каждого снаряда
 * 
 * 2. Соответствие индексов:
 *    - projectilePrefabs[0] использует projectileIcons[0]
 *    - projectilePrefabs[1] использует projectileIcons[1]
 *    - И так далее...
 * 
 * 3. Fallback система:
 *    Если иконка не назначена в массиве, система попытается найти её в префабе:
 *    - SpriteRenderer на корневом объекте
 *    - SpriteRenderer в дочерних объектах
 * 
 * ПРИМЕР НАСТРОЙКИ:
 * =================
 * 
 * projectilePrefabs:     projectileIcons:
 * [0] BulletPrefab    -> [0] bullet_icon.png
 * [1] RocketPrefab    -> [1] rocket_icon.png  
 * [2] HomingPrefab    -> [2] homing_icon.png
 * [3] KinematicPrefab -> [3] sniper_icon.png
 * 
 * ПРОВЕРКИ И ПРЕДУПРЕЖДЕНИЯ:
 * ==========================
 * 
 * Система автоматически проверяет:
 * - Соответствие количества префабов и иконок
 * - Наличие пустых иконок в массиве
 * - Выводит предупреждения в консоль при проблемах
 * 
 * ПРОГРАММНОЕ УПРАВЛЕНИЕ:
 * ======================
 * 
 * // Установить иконку для снаряда
 * inventory.SetProjectileIcon(0, newIconSprite);
 * 
 * // Получить иконку снаряда
 * Sprite icon = inventory.GetProjectileIcon(0);
 * 
 * // Обновить все иконки
 * inventory.RefreshIcons();
 * 
 * РЕКОМЕНДАЦИИ:
 * =============
 * 
 * 1. Используйте иконки размером 64x64 или 128x128 пикселей
 * 2. Сохраняйте иконки в папке Resources для удобства загрузки
 * 3. Названия иконок должны соответствовать типу снаряда
 * 4. Проверяйте консоль на предупреждения после настройки
 * 
 * ПРИМЕРЫ ИКОНОК:
 * ===============
 * 
 * - bullet_icon.png - обычный снаряд
 * - rocket_icon.png - ракета  
 * - homing_icon.png - самонаводящийся
 * - sniper_icon.png - кинематический
 * - explosive_icon.png - взрывчатка
 * - laser_icon.png - лазер
 */


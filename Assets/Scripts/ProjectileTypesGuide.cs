/*
 * РУКОВОДСТВО ПО ТИПАМ СНАРЯДОВ
 * =============================
 * 
 * В проекте доступны 3 типа снарядов:
 * 
 * 1. PROJECTILE (базовый)
 *    - Физический снаряд с гравитацией
 *    - При попадании в VoxelChunk16 запускается таймер взрыва (3 сек)
 *    - Во время таймера снаряд мигает и продолжает кататься
 *    - Цепные реакции между снарядами
 *    - Большой радиус взрыва
 *    - Автоматический взрыв по истечении времени жизни (maxLifetime)
 * 
 * 2. KINEMATIC_PROJECTILE (прямолинейный)
 *    - Летает по прямой без гравитации
 *    - Постоянная скорость полета
 *    - Взрывается сразу при попадании
 *    - Минимальный радиус взрыва (0.2f)
 *    - Нет цепных реакций
 *    - Автоматический взрыв по истечении времени жизни (maxLifetime)
 *    - Идеален для точных выстрелов
 * 
 * 3. HOMING_PROJECTILE (самонаводящийся)
 *    - Ищет цель по тегу и слою
 *    - Наводится на ближайшую цель в радиусе
 *    - Взрывается при попадании или приближении к цели
 *    - Настраиваемая скорость поворота
 *    - Идеален для поражения движущихся целей
 *    
 *    ПОВЕДЕНИЕ БЕЗ ЦЕЛИ:
 *    - Летит прямо в направлении создания
 *    - Может постоянно искать новые цели (searchContinuously)
 *    - Может самоуничтожаться через время (selfDestructIfNoTarget)
 *    - Можно задать фиксированную цель (fixedTarget)
 *    - Автоматический взрыв по истечении времени жизни (maxLifetime)
 * 
 * 4. ROCKET_PROJECTILE (ракета)
 *    - Летит с ускорением до максимальной скорости
 *    - Имеет небольшие случайные отклонения в полете
 *    - Вращается вокруг оси движения
 *    - Взрывается сразу при попадании с силой удара
 *    - Поддерживает визуальные эффекты (след, двигатель, свет)
 *    - Автоматический взрыв по истечении времени жизни (maxLifetime)
 *    - Идеален для разрушения укреплений и групп врагов
 * 
 * НАСТРОЙКА В ИНВЕНТАРЕ:
 * =====================
 * 
 * 1. Создайте префабы для каждого типа снарядов
 * 2. Добавьте соответствующий компонент (Projectile, KinematicProjectile, HomingProjectile, RocketProjectile)
 * 3. Настройте параметры в инспекторе
 * 4. Добавьте префабы в массив ProjectileInventory.projectilePrefabs
 * 5. Создайте иконки для отображения в UI
 * 
 * ПРИМЕРЫ ИСПОЛЬЗОВАНИЯ:
 * ======================
 * 
 * - Обычный снаряд: для разрушения зданий и создания кратеров
 * - Кинематический: для снайперских выстрелов и точного поражения
 * - Самонаводящийся: для поражения мобильных целей и роботов
 * - Ракета: для разрушения укреплений и массового поражения
 * 
 * ПАРАМЕТРЫ НАСТРОЙКИ:
 * ====================
 * 
 * Время жизни (для всех типов):
 * - maxLifetime: максимальное время жизни в секундах (настраивается в базовом классе)
 * - destroyOnLifetime: уничтожать снаряд по истечении времени (true)
 * - KinematicProjectile: 8 секунд
 * - HomingProjectile: 12 секунд  
 * - RocketProjectile: 15 секунд
 * - Projectile: 10 секунд (по умолчанию)
 * 
 * KinematicProjectile:
 * - speed: скорость полета (рекомендуется 15-25)
 * - ignoreGravity: игнорировать гравитацию (true)
 * - directHitRadius: радиус прямого попадания (0.1-0.5)
 * 
 * HomingProjectile:
 * - speed: скорость полета (рекомендуется 10-20)
 * - turnSpeed: скорость поворота (рекомендуется 60-120)
 * - maxTurnAngle: максимальный угол поворота за кадр (30-60)
 * - homingRadius: радиус поиска цели (30-100)
 * - targetTag: тег цели ("Enemy", "Player", etc.)
 * - targetLayerMask: слой целей
 * - explosionRadius: радиус взрыва при попадании (2-5)
 * - proximityDistance: расстояние взрыва приближения (1-3)
 * 
 * Поведение без цели:
 * - searchContinuously: искать цель постоянно (true)
 * - searchInterval: интервал поиска в секундах (0.5)
 * - selfDestructIfNoTarget: самоуничтожение без цели (false)
 * - selfDestructTime: время до самоуничтожения (10)
 * - fixedTarget: фиксированная цель (опционально)
 * 
 * RocketProjectile:
 * - speed: начальная скорость (20-30)
 * - acceleration: ускорение (3-8)
 * - maxSpeed: максимальная скорость (30-50)
 * - deviationStrength: сила отклонений (0.3-1.0)
 * - deviationFrequency: частота отклонений (1-3)
 * - rotationSpeed: скорость вращения (120-300)
 * - explosionRadius: радиус взрыва (3-6)
 * - impactForce: сила удара (30-80)
 * - ignoreGravity: игнорировать гравитацию (false для реализма)
 */

